import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
// The knob data lives in the manifest, not here: build.mjs is not in the npm
// `files` list, so this import cannot leak docs/ to a consumer. Kept at the
// top per R-2, with the other imports, rather than beside its one user.
import { KNOBS } from '../docs/manifest/knobs.mjs'
import { ICON_ENTRIES } from '../docs/manifest/icons.mjs'

// The shipped artifact is one file, but the sources are split by
// responsibility so they stay readable. Order matters and is declared here
// rather than inferred from the directory listing: tokens must land before
// anything that references them, and later layers deliberately override
// earlier ones (a shell restyles a primitive it contains). Alphabetical order
// would put `base` before `tokens` and quietly break the cascade.
// forms.css follows primitives.css because `textarea.axi-input` restyles a
// primitive defined there; feedback.css follows data.css because
// `.axi-meter--busy` modifies a data component. A later file may restyle an
// earlier one, never the reverse.
export const ORDER = ['tokens.css', 'base.css', 'primitives.css', 'forms.css', 'layout.css', 'shells.css', 'data.css', 'feedback.css', 'prose.css']

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const BANNER = `/* axi design language - generated by scripts/build.mjs.
   Edit the files in src/ and run \`npm run build\`; do not edit this file. */
`

export function buildCss(order = ORDER) {
  const parts = order.map((name) => {
    const source = readFileSync(resolve(ROOT, 'src', name), 'utf8').trimEnd()
    return `/* --- ${name} --- */\n${source}`
  })
  return `${BANNER}\n${parts.join('\n\n')}\n`
}

// The accents are data, not stylesheet source: accents.json is the single
// source of truth and this generation is the only way dist/accents.css comes
// to exist. It cannot live as src/accents.css - ORDER must match src/ exactly
// and colour literals are forbidden outside tokens.css; accents are the
// second sanctioned home for colour literals precisely because they are
// generated from the data file. Opt-in: never concatenated into axi.css.
export const ACCENTS = JSON.parse(readFileSync(resolve(ROOT, 'accents.json'), 'utf8'))

export function buildAccentsCss(accents = ACCENTS) {
  const rules = accents
    .map((a) => `[data-axi-accent="${a.id}"] { --axi-accent: ${a.hex}; }`)
    .join('\n')
  return `${BANNER}\n${rules}\n`
}

// A theme is a repaint of the language, never an extension of it: the Themes
// section of docs/RULES.md has the whole rule, and tests/themes.test.mjs
// enforces it against the generated file. Generated for the same reason the
// accents are - themes/*.json is the source of truth and the third sanctioned
// home for a colour literal, after tokens.css and accents.json, because it is
// data the build generates from rather than stylesheet source. It cannot live
// in src/: ORDER must match src/ exactly, and a theme must never be
// concatenated into axi.css. Opt-in, one file per theme, so a consumer that
// wants only the language pays nothing for a theme it does not import.
export const THEMES = readdirSync(resolve(ROOT, 'themes'))
  .filter((f) => f.endsWith('.json'))
  .sort()
  .map((f) => JSON.parse(readFileSync(resolve(ROOT, 'themes', f), 'utf8')))

export function buildThemeCss(theme) {
  const body = Object.entries(theme.tokens)
    .map(([name, value]) => `  ${name}: ${value};`)
    .join('\n')
  return `${BANNER}\n[data-axi-theme="${theme.id}"] {\n${body}\n}\n`
}

// The icon set is the third kind of repo data the build turns into a dist/
// artifact, after the accents and the themes, and it follows their contract:
// icons/ is the source of truth, dist/icons/ is generated, and nothing
// hand-edits the generated file. The source SVGs are read as text rather than
// parsed - tests/icons.test.mjs owns the geometry, and a second parser here
// would be a second opinion about what the drawing says.
const ICON_DIR = resolve(ROOT, 'icons')

// Everything between the source <svg ...> and its </svg>: the drawing, without
// the canvas and stroke attributes, which the symbol restates once.
const iconBody = (svg) =>
  svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .trim()

// Sorted by name, not by filename: '-' sorts before '.', so sorting the
// directory listing would put check-check.svg ahead of check.svg while every
// other ordering in the set - the manifest, icons.json, the docs grid - sorts
// the bare names. One of those orders has to be the order.
export const ICONS = readdirSync(ICON_DIR)
  .filter((f) => f.endsWith('.svg') && !f.startsWith('.'))
  .map((f) => ({
    name: f.replace(/\.svg$/, ''),
    body: iconBody(readFileSync(resolve(ICON_DIR, f), 'utf8')),
  }))
  .sort((a, b) => (a.name < b.name ? -1 : 1))

// A Lucide name this set answers to under another name. `aliases` is search
// metadata and stays out of the sprite - 65 words like `done` and `back` would
// add ~10KB to an 11.7KB file and turn every one of them into public API.
// These are names an app is already holding in its source, and the payoff is
// that porting off lucide-react is a rename rather than a call-site audit.
export function aliasPairs(entries = ICON_ENTRIES) {
  return entries
    .flatMap((e) => (e.lucide ?? []).map((alias) => ({ alias, canonical: e.name })))
    .sort((a, b) => (a.alias < b.alias ? -1 : 1))
}

// One request for the whole set. The stroke attributes sit on each <symbol>
// rather than on the sprite root, because <use> instantiates the symbol and
// an attribute on the root would not travel into the instance.
//
// A <use> into a *separate* document has historically not inherited the host
// page's `color` in every engine, which would render the whole set black on a
// near-black page. Measured rather than assumed, 2026-09-28: Chromium 150 over
// http:// inherits `currentColor` through an external reference, and the host
// <svg> needs no viewBox of its own - the symbol carries it. So
// `<use href="sprite.svg#axi-name">` is the documented consumer pattern. The
// docs site still inlines this sprite (docs/site/shell.mjs) for a different
// reason: its pages live at several depths and a bare `#axi-name` fragment
// needs no path arithmetic.
//
// An alias symbol's body is a <use> at the canonical symbol, which is a
// reference *within* the sprite document resolved through a reference *into*
// it - two levels of indirection, and the second one unmeasured until now.
// Measured rather than assumed, 2026-09-28: Chromium 150 over http:// draws
// `<use href="sprite.svg#axi-triangle-alert">` identically to the canonical
// glyph and still inherits the host page's `color` through both hops. If that
// ever stops being true, copy `icon.body` into the alias symbol instead; the
// consumer contract does not change either way.
export function buildIconSprite(icons = ICONS, aliases = aliasPairs()) {
  const symbol = (id, body) => `  <symbol id="axi-${id}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="3" stroke-linejoin="miter">
${body}
  </symbol>`
  const drawings = icons.map((icon) =>
    symbol(
      icon.name,
      icon.body
        .split('\n')
        .map((line) => `    ${line.trim()}`)
        .join('\n'),
    ),
  )
  const links = aliases.map(({ alias, canonical }) => symbol(alias, `    <use href="#axi-${canonical}"/>`))
  return `<svg xmlns="http://www.w3.org/2000/svg">
<!-- axi design language - generated by scripts/build.mjs from icons/.
     Edit the files in icons/ and run \`npm run build\`; do not edit this file. -->
${[...drawings, ...links].join('\n')}
</svg>
`
}

// The manifest, as data a consumer can read: an icon picker in an app should
// not have to import from docs/.
// dist/icons/ is generated, so the build owns every file in it - including the
// ones that should no longer be there. Renaming an icon otherwise leaves the
// old drawing behind, committed and published: a glyph the catalogue does not
// list, that no drift test mentions, because every check ran icons/ -> dist/
// and never the other way. Named rather than inlined so the reverse direction
// is testable without a build.
export function staleIconFiles(present, icons = ICONS) {
  const claimed = new Set(['sprite.svg', 'icons.json', ...icons.map((i) => `${i.name}.svg`)])
  return present.filter((f) => !claimed.has(f))
}

export function buildIconsJson(entries = ICON_ENTRIES) {
  return `${JSON.stringify([...entries].sort((a, b) => (a.name < b.name ? -1 : 1)), null, 2)}\n`
}

// The knob table is generated into README.md between markers. It is the one
// table in this repo describing src/ that a human used to maintain by hand,
// and the one that could therefore go stale with no symptom at all - nothing
// imports a README.
export function buildKnobTable(knobs = KNOBS) {
  const rows = knobs.map((k) => `| \`${k.name}\` | ${k.sets} | ${k.fallback} | \`${k.example}\` |`)
  return ['| Knob | Sets | Fallback | Example |', '|---|---|---|---|', ...rows].join('\n')
}

export function writeKnobTable(readme) {
  return readme.replace(
    /(<!-- axi:knobs -->\n)[\s\S]*?(\n<!-- \/axi:knobs -->)/,
    (_, open, close) => `${open}${buildKnobTable()}${close}`,
  )
}

// Only write when run directly, so importing this from a test never has the
// side effect of rewriting the artifact the test is about to check.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(resolve(ROOT, 'dist'), { recursive: true })
  writeFileSync(resolve(ROOT, 'dist/axi.css'), buildCss())
  console.log(`built dist/axi.css from ${ORDER.length} source(s)`)
  writeFileSync(resolve(ROOT, 'dist/accents.css'), buildAccentsCss())
  console.log(`built dist/accents.css from ${ACCENTS.length} accent(s)`)

  mkdirSync(resolve(ROOT, 'dist/themes'), { recursive: true })
  for (const theme of THEMES) {
    writeFileSync(resolve(ROOT, `dist/themes/${theme.id}.css`), buildThemeCss(theme))
  }
  console.log(`built dist/themes/ from ${THEMES.length} theme(s)`)

  mkdirSync(resolve(ROOT, 'dist/icons'), { recursive: true })
  writeFileSync(resolve(ROOT, 'dist/icons/sprite.svg'), buildIconSprite())
  for (const icon of ICONS) {
    writeFileSync(
      resolve(ROOT, `dist/icons/${icon.name}.svg`),
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="3" stroke-linejoin="miter">\n${icon.body}\n</svg>\n`,
    )
  }
  writeFileSync(resolve(ROOT, 'dist/icons/icons.json'), buildIconsJson())
  for (const stale of staleIconFiles(readdirSync(resolve(ROOT, 'dist/icons')))) {
    rmSync(resolve(ROOT, `dist/icons/${stale}`), { recursive: true })
    console.log(`removed stale dist/icons/${stale}`)
  }
  console.log(`built dist/icons/ from ${ICONS.length} icon(s)`)

  const readmePath = resolve(ROOT, 'README.md')
  writeFileSync(readmePath, writeKnobTable(readFileSync(readmePath, 'utf8')))
  console.log(`wrote the knob table into README.md (${KNOBS.length} knobs)`)
}
